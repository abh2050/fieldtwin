"""Write the Gate 7 reports from the recorded results. Every figure is SYNTHETIC or a modeled estimate."""

from __future__ import annotations

import json
from pathlib import Path

from pipelines.acquire.common import core

from .run import RESULTS

DECISION_REPORT = Path("reports") / "decision" / "decision_engine.md"
ECONOMICS_REPORT = Path("reports") / "economics" / "scheduling_comparison.md"
NAMES = {"FIXED": "Fixed rounds", "RISK_BASED": "Risk-based", "ROUTE_OPTIMIZED": "Route-optimized"}


def _money(x: float) -> str:
    sign = "−" if x < 0 else ""
    return f"{sign}${abs(x):,.0f}"


def decision_report(root: Path) -> str:
    d = json.loads((root / RESULTS / "decisions.json").read_text())
    rules = core.load_yaml(root / "config" / "decision" / "gate7_rules.yaml")
    grades = {g["recommendation_id"]: g for g in d["grades"]}
    rows = []
    for scenario_id, info in d["scenarios"].items():
        recs = [r for r in d["recommendations"] if r["scenario_id"] == scenario_id]
        if not recs:
            rows.append(f"| {scenario_id} | {info['category']} | 0 | — | — | — | No alarm |")
        for r in recs:
            g = grades[r["recommendation_id"]]
            target = r["candidate_assets"][0] if r["candidate_assets"] else "—"
            band = (
                f"{r['priority_score']}, {r['priority_band']}"
                if r["priority_band"]
                else str(r["priority_score"])
            )
            rows.append(
                f"| {scenario_id} | {info['category']} | {info['alarms']} | {r['decided_at'][:16].replace('T', ' ')} | "
                f"{r['action']} | {target} ({band}) | {g['outcome']} |"
            )
    dispatched = [g for g in d["grades"] if g["work_order_id"]]
    right = sum(1 for g in dispatched if g["work_order_targets_faulted_asset"])
    return f"""# Decision engine on the six AETHER field scenarios

Generated by `pipelines/decision/reports.py` from `results/decisions.json`. Everything here is SYNTHETIC: fictional assets, simulated telemetry, and simulated work orders. No equipment is actuated.

## How a recommendation is made

1. The Gate 5 detector (`{d["model"]["model_id"]}`, bundle `{d["model"]["sha256"][:16]}…`) runs on each scenario's telemetry through the streaming engine, as an operator's system would. Each alarm start carries the three sensors furthest from training normal.
2. The rules in `config/decision/gate7_rules.yaml` (version {d["rules_version"]}) turn an alarm into a recommendation. Inputs are what an operator would know: the alarm, the planned-operations calendar, open inspection requests, and the network's consequence shares. Simulator truth is never an input.
3. The priority score is a sum of named integer terms: {rules["evidence"]["alarm_started"]} for an alarm start, up to {rules["evidence"]["repeat_alarm_cap"]} for repeats, up to {rules["evidence"]["age_cap"]} for age, up to {rules["consequence"]["points_max"]} for consequence (share of the field's wells flowing through the asset), and {rules["evidence"]["open_inspection_request"]} for an open inspection request. Bands: P1 from 60, P2 from 40, P3 below. A detector score only gates "an alarm started"; it is never read as a failure probability.
4. Only FIELD_INSPECTION and CHECK_INSTRUMENTATION create work orders. The engine creates; only a maintenance supervisor may approve, reject, or request evidence.

## Results

| Scenario | Category | Alarms | Decided at | Action | Target (score, band) | Outcome against truth |
|---|---|---:|---|---|---|---|
{chr(10).join(rows)}

- **{right} of {len(dispatched)} dispatches went to the faulted asset.** The restriction went to GS-A and the compressor derate to C-01.
- **One dispatch was a false alarm, and it scored highest.** In the planned-shutdown scenario the first alarm fell inside the declared shutdown and was suppressed. The second came 45 minutes after the shutdown window ended, as Pad B came back. Nothing in the rules covers a restart transient, so it was dispatched, and its repeated-alarm and age points made it the highest score of the run. The rules were not changed to hide this.
- **The sensor-drift scenario produced no alarm**, so no recommendation exists. Only a scheduled visit could find it.
- **Localization is weak.** The evidence sensors' deviations are small and close together. In the compressor case C-01 ranked second (deviation 0.098, below well A-03 at 0.112), so the correct target came from rules version 3's consequence ordering, not from the evidence. In the restriction case GS-A led clearly (0.32 against 0.14).
- **Approvals were scripted.** Every work order was approved and completed by scripted demonstration actors under a fixed approve-all policy that never reads truth (`config/decision/demo_decisions.yaml`). They are recorded as `SCRIPTED_DEMO`, never as human decisions. A person's decisions go through `pipelines/decision/decide.py`, recorded as `HUMAN`.

The full chain for each recommendation, from source records to outcome, is in the [evidence audit](evidence_audit.md).

## Rule versions

| Version | Change | When |
|---:|---|---|
| 1 | Committed rules | Before any alarm or recommendation |
| 2 | The data-quality rule named sensor statuses the simulator never emits; it now uses the contract's quality values | Before any alarm or recommendation |
| 3 | A work order targets the candidate with the largest consequence share; code had taken the first evidence sensor's asset | After the scenario alarms were seen, before any recommendation |
"""


def economics_report(root: Path) -> str:
    e = json.loads((root / RESULTS / "economics.json").read_text())
    cfg = core.load_yaml(root / "config" / "decision" / "economics.yaml")
    s = e["summary"]
    rows = []
    for k in ("FIXED", "RISK_BASED", "ROUTE_OPTIMIZED"):
        x = s[k]
        rows.append(
            f"| {NAMES[k]} | {_money(x['total']['mean'])} ({_money(x['total']['p5'])} to {_money(x['total']['p95'])}) | "
            f"{_money(x['labor']['mean'])} | {_money(x['travel']['mean'])} | {_money(x['deferred_production']['mean'])} | "
            f"{x['site_visits']['mean']:.0f} | {x['alarm_trips']['mean']:.1f} | {x['trips_finding_nothing']['mean']:.1f} | "
            f"{x['mean_hours_to_repair']['mean'] / 24:.1f} |"
        )
    diffs = []
    for k in ("RISK_BASED", "ROUTE_OPTIMIZED"):
        x = s[k]["total_minus_fixed"]
        diffs.append(
            f"| {NAMES[k]} minus fixed | {_money(x['mean'])} | {_money(x['p5'])} to {_money(x['p95'])} | "
            f"{100 * x['share_of_replicates_cheaper']:.0f}% |"
        )
    x = s["ROUTE_OPTIMIZED"]["total_minus_risk_based"]
    diffs.append(
        f"| Route-optimized minus risk-based | {_money(x['mean'])} | {_money(x['p5'])} to {_money(x['p95'])} | "
        f"{100 * x['share_of_replicates_cheaper']:.0f}% |"
    )
    sens = [
        f"| `{r['assumption']}` | ×{r['factor']:g} | "
        + " | ".join(_money(r["mean_total"][k]) for k in ("FIXED", "RISK_BASED", "ROUTE_OPTIMIZED"))
        + f" | {NAMES[r['cheapest']]} |"
        for r in e["sensitivity"]
    ]
    det = e["detector"]
    return f"""# Inspection scheduling: a modeled comparison

> **Modeled scenario estimates for a fictional facility.** Every figure below comes from a simulation of fictional AETHER Field under declared assumptions (`config/decision/economics.yaml`, version {e["economics_version"]}). None is a realized saving, an expected saving, or a forecast for any real operation.

Generated by `pipelines/decision/reports.py` from `reports/decision/results/economics.json`.

## Setup

- **Horizon and replicates:** {e["horizon_days"]} days, {e["replicates"]} replicates, seed {e["seed"]}. Each replicate draws one year of faults and false alarms; all three strategies face the same draw, so their differences come from scheduling.
- **Assets:** {len(e["assets"])} fictional assets at {len(e["sites"])} inspection sites (12 well pads, 3 gathering segments, the compressor station), located on the Gate 4 network. Nominal flow through each asset is its median in the Gate 4 normal run.
- **Faults (assumed):** {", ".join(f"{k} {v}" for k, v in cfg["fault_rate_per_asset_year"].items())} per asset per year; {100 * cfg["sensor_fault_share"]:.0f}% are sensor faults with no production loss. A physical fault defers {100 * cfg["production"]["deferred_share_while_faulted"]:.0f}% of the flow through its asset at ${cfg["production"]["gas_price_per_mcf"]:.2f} per Mcf until repaired.
- **Detector (measured in Gate 5, held-out regimes):** detection share {", ".join(f"{k} {v:.2f}" for k, v in det["detect_share"].items())}; delays drawn between the Gate 5 quartiles; {det["false_alarms_per_hour"] * 8760:.1f} false alarms a year. Wells and flowlines borrow the restriction results, an assumption, because Gate 5 has no well-specific category. {100 * cfg["localization_correct"]:.0f}% of real-fault alarms are assumed to target the faulted asset.
- **Field work (assumed):** one crew, {cfg["labor"]["hours_per_day"]:g} h a day, {cfg["inspection"]["on_site_hours"]:g} h on site, {100 * cfg["inspection"]["finds_physical_fault"]:.0f}% chance an inspection finds a physical fault, {cfg["inspection"]["repair_days"]} day to repair, ${cfg["labor"]["cost_per_hour"]:.0f} an hour, ${cfg["travel"]["cost_per_km"]:.2f} a km at {cfg["travel"]["speed_km_per_h"]:g} km/h with a {cfg["travel"]["road_factor"]:g} road factor.
- **Strategies:** fixed rounds every {cfg["strategies"]["FIXED"]["cycle_days"]} days in a fixed geographic order; risk-based dispatch on each approved alarm ({cfg["strategies"]["RISK_BASED"]["approval_delay_h"]:g} h approval delay), one out-and-back trip each, plus a round every {cfg["strategies"]["RISK_BASED"]["fallback_cycle_days"]} days; route-optimized, the same triggers with each day's alarms and round stops routed together by OR-Tools ({e["solver_calls_main"]:.0f} distinct tours solved in the main run).

## Results

Mean per year, with the 5th to 95th percentile across replicates for the total.

| Strategy | Total | Labor | Travel | Deferred production | Site visits | Alarm trips | Trips finding nothing | Days to repair |
|---|---|---:|---:|---:|---:|---:|---:|---:|
{chr(10).join(rows)}

Paired differences, replicate by replicate:

| Comparison | Mean | 5th to 95th percentile | Replicates cheaper |
|---|---:|---|---:|
{chr(10).join(diffs)}

**Under these assumptions, fixed monthly rounds cost least on average.** Risk-based dispatch saves labor, but with the selected detector catching about half of restrictions, stretching rounds to 90 days leaves physical faults running longer, and deferred production dominates the cost. The spread is wide because a single fault on the trunk segment can dominate a year. **Route optimization changes almost nothing**: the field is about 4 km across and a day holds four or five stops, so there is little travel to save.

## Sensitivity

Each assumption scaled by ×0.5 and ×2 with everything else fixed. Probabilities are capped at 1.

| Assumption | Factor | Fixed | Risk-based | Route-optimized | Cheapest |
|---|---:|---:|---:|---:|---|
{chr(10).join(sens)}

Fixed rounds stay cheapest on average under every single change tried. That is a statement about these assumptions together, not about inspection strategy in general.

## Limitations

1. Every rate, cost, and probability is assumed for a fictional field. Only the detector's behaviour and the network's flows come from earlier gates, and both are themselves synthetic.
2. A dispatch that finds nothing produces no second alarm in this model, although a real detector would keep alarming on a persisting fault. That favours fixed rounds.
3. Detection delays are drawn between Gate 5 quartiles, and Gate 5's held-out regimes are themselves a small synthetic benchmark.
4. A strategy mixing alarm dispatch with monthly rounds wasn't declared before the run, so it isn't reported.
5. Crew capacity, travel, and repair are simplified: one crew, straight-line distances with a road factor, and repairs that always succeed once a fault is found.
"""


def run(root: Path = core.REPO_ROOT) -> list[str]:
    (root / DECISION_REPORT).parent.mkdir(parents=True, exist_ok=True)
    (root / DECISION_REPORT).write_text(decision_report(root))
    (root / ECONOMICS_REPORT).parent.mkdir(parents=True, exist_ok=True)
    (root / ECONOMICS_REPORT).write_text(economics_report(root))
    return [str(DECISION_REPORT), str(ECONOMICS_REPORT)]


if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
