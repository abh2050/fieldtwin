"""The evidence audit (UC-08): for every recommendation, the chain from source records to outcome.

Everything is read back from the database, so the audit shows what was stored, not what the pipeline
meant to store. Outcomes come from the grading in reports/decision/results/decisions.json, which is
the only place simulator truth is used.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import psycopg

from packages.repositories.database import REPO_ROOT, connect

from .run import RESULTS

OUT = Path("reports") / "decision" / "evidence_audit.md"


def chain(conn: psycopg.Connection, recommendation_id: str) -> dict[str, Any]:
    rec = conn.execute(
        """SELECT r.recommendation_id, r.action, r.candidate_assets, r.suppressed_assets, r.priority_score,
                  r.priority_band, r.respond_within_h, r.terms, r.explanation, r.rules_version, r.decided_at,
                  a.alarm_id, a.started_at, a.score, a.threshold, a.model_id, a.model_version, a.model_sha256,
                  a.evidence, a.provenance_class, a.input_provenance,
                  s.scenario_run_id, s.scenario_id, s.simulator_name, s.simulator_version, s.config_sha256,
                  s.output_sha256, s.random_seed, s.output_uri, s.target_asset_id, s.affected_asset_id
             FROM recommendations r JOIN detector_alarms a USING (alarm_id)
             JOIN scenario_runs s ON s.scenario_run_id = r.scenario_run_id
            WHERE r.recommendation_id = %s""",
        (recommendation_id,),
    ).fetchone()
    if rec is None:
        raise KeyError(recommendation_id)
    names = [
        "recommendation_id",
        "action",
        "candidate_assets",
        "suppressed_assets",
        "priority_score",
        "priority_band",
        "respond_within_h",
        "terms",
        "explanation",
        "rules_version",
        "decided_at",
        "alarm_id",
        "alarm_started_at",
        "score",
        "threshold",
        "model_id",
        "model_version",
        "model_sha256",
        "evidence",
        "alarm_provenance",
        "alarm_input_provenance",
        "scenario_run_id",
        "scenario_id",
        "simulator_name",
        "simulator_version",
        "config_sha256",
        "output_sha256",
        "random_seed",
        "output_uri",
        "scenario_target",
        "scenario_affected",
    ]
    row = dict(zip(names, rec, strict=True))
    row["series"] = conn.execute(
        """SELECT transformation_id, provenance_class::text, count(*) FROM observations
            WHERE scenario_run_id = %s GROUP BY 1, 2 ORDER BY 1""",
        (row["scenario_run_id"],),
    ).fetchall()
    row["transformation_text"] = dict(
        conn.execute(
            "SELECT transformation_id, description FROM transformations WHERE transformation_id = ANY(%s)",
            ([t for t, _, _ in row["series"]],),
        ).fetchall()
    )
    order = conn.execute(
        "SELECT work_order_id, external_id, asset_id, status FROM work_orders WHERE recommendation_id = %s",
        (recommendation_id,),
    ).fetchone()
    row["work_order"] = order
    row["transitions"] = (
        conn.execute(
            """SELECT t.sequence, t.decision, t.from_status, t.to_status, t.actor_id, t.actor_kind, t.actor_role,
                      t.justification, t.decided_at, (e.event_id IS NOT NULL)
                 FROM work_order_transitions t
                 LEFT JOIN audit_events e ON e.correlation_id = 'transition:' || t.transition_id
                WHERE t.work_order_id = %s ORDER BY t.sequence""",
            (order[0],),
        ).fetchall()
        if order
        else []
    )
    return row


def render(conn: psycopg.Connection, root: Path = REPO_ROOT) -> str:
    results = json.loads((root / RESULTS / "decisions.json").read_text())
    grades = {g["recommendation_id"]: g for g in results["grades"]}
    rules_path = "config/decision/gate7_rules.yaml"
    lines = [
        "# Evidence audit",
        "",
        "Generated by `pipelines/decision/audit.py` from the database. One section per recommendation, following "
        "use case UC-08: source records, transformations, scenario mapping, model version, rule output, "
        "assumptions, decision, and outcome. Everything here concerns fictional AETHER assets in simulated "
        "scenarios and is SYNTHETIC or INFERRED.",
        "",
        "**About the decisions.** No person reviewed these work orders. Approvals and completions were made by "
        "scripted demonstration actors (`SCRIPTED_DEMO`) under a fixed approve-all policy that never reads "
        "simulator truth (`config/decision/demo_decisions.yaml`). They show the workflow, not anyone's judgment.",
        "",
    ]
    for rec in results["recommendations"]:
        c = chain(conn, rec["recommendation_id"])
        grade = grades[rec["recommendation_id"]]
        lines += [
            f"## {c['scenario_id']}: {c['action']} at {c['decided_at']:%Y-%m-%d %H:%M}",
            "",
            f"Recommendation `{c['recommendation_id']}` from alarm `{c['alarm_id']}`.",
            "",
            "**Source records.** Scenario run "
            f"`{c['scenario_run_id']}`, simulator `{c['simulator_name']}` v{c['simulator_version']}, seed "
            f"{c['random_seed']}, configuration `{c['config_sha256'][:16]}…`, output `{c['output_sha256'][:16]}…` "
            f"(`{c['output_uri']}`). "
            + "; ".join(f"{n} {p} series by `{t}`" for t, p, n in c["series"])
            + ".",
            "",
            "**Transformations.** "
            + " ".join(f"`{t}`: {d}" for t, d in c["transformation_text"].items())
            + f" The alarm is {c['alarm_provenance']} from {c['alarm_input_provenance']} telemetry; the recommendation is SYNTHETIC.",
            "",
            f"**Scenario mapping.** The scenario declares target `{c['scenario_target']}` and affected asset "
            f"`{c['scenario_affected']}`. The engine never read these; they appear here only for the audit.",
            "",
            f"**Model.** `{c['model_id']}` v{c['model_version']}, bundle SHA-256 `{c['model_sha256'][:16]}…`. "
            f"Alarm score {c['score']:.3f} against threshold {c['threshold']:.3f}. Evidence sensors: "
            + ", ".join(
                f"`{e['tag']}` ({e['asset_id']}, deviation {e['deviation']:.3f})"
                for e in c["evidence"]
            )
            + ".",
            "",
            "**Rule output.**",
            "",
            *[f"- {line}" for line in c["explanation"]],
            "",
            "| Term | Points | Input | Rule |",
            "|---|---:|---|---|",
            *[
                f"| {t['name']} | {t['points']} | {t['input']} | `{t['rule']}` |"
                for t in c["terms"]
            ],
            "",
            f"**Assumptions.** Rules version {c['rules_version']} in `{rules_path}`. Consequence shares come from the "
            "Gate 4 network graph. A detector score is never read as a failure probability.",
            "",
        ]
        if c["work_order"]:
            _, external, asset, status = c["work_order"]
            lines += [
                f"**Decision.** Work order `{external}` on `{asset}`, now {status}.",
                "",
                "| # | Decision | From | To | Actor | Kind | Audit event |",
                "|---:|---|---|---|---|---|---|",
                *[
                    f"| {t[0]} | {t[1]} | {t[2] or '-'} | {t[3]} | {t[4]} ({t[6]}) | {t[5]} | {'yes' if t[9] else 'MISSING'} |"
                    for t in c["transitions"]
                ],
                "",
            ]
        else:
            lines += ["**Decision.** No work order: the recommendation doesn't dispatch.", ""]
        lines += [
            f"**Outcome (graded against simulator truth after the fact).** {grade['outcome']}. "
            f"Scenario category {grade['scenario_category']}; faulted assets: "
            + (", ".join(f"`{a}`" for a in grade["faulted_assets"]) or "none")
            + ".",
            "",
        ]
    missed = results["faults_without_alarm"]
    if missed:
        lines += ["## Faults with no alarm", ""]
        lines += [
            f"- {m['scenario_id']} ({m['category']}, faulted {', '.join(m['faulted_assets'])}): the detector never "
            "alarmed, so no recommendation exists. Only a scheduled visit could find it."
            for m in missed
        ]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    with connect() as conn:
        text = render(conn)
    (REPO_ROOT / OUT).parent.mkdir(parents=True, exist_ok=True)
    (REPO_ROOT / OUT).write_text(text)
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
