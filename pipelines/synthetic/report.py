"""Generate the AETHER-FAULT-001 report from a deterministic run. It needs no database."""

from __future__ import annotations

from packages.repositories.database import REPO_ROOT
from packages.scenario_engine.config import ScenarioConfig, load_config
from pipelines.synthetic.aether_fault_001 import execute

REPORT = REPO_ROOT / "reports" / "scenarios" / "aether_fault_001.md"
PA_TO_PSI = 0.00014503773773
SM3S_TO_KSM3D = 86.4
DAY = 86400


def _psi(pascals: float) -> str:
    return f"{pascals * PA_TO_PSI:,.0f}"


def _stable(measured: str) -> str:
    """Residuals near machine precision differ between CPUs, so the report states a bound."""
    try:
        value = abs(float(measured))
    except ValueError:
        return measured
    return "below 1e-12" if value < 1e-12 else measured


def render(config: ScenarioConfig) -> str:
    results = execute(config)
    nominal = results["nominal"][0]
    fault = results["fault"][0]
    frame = fault.frame
    schedule = config.restriction
    well, segment, gas = config.well, config.gathering_segment, config.gas
    ambient = config.ambient.pressure_pa_abs
    interval = config.sampling.interval_s

    days = sorted(
        {
            0,
            schedule.onset_offset_s // DAY,
            3,
            4,
            5,
            schedule.full_severity_offset_s // DAY,
            config.sampling.duration_s // DAY - 1,
        }
    )
    lines = [
        "# AETHER-FAULT-001: Progressive Gathering-Line Restriction",
        "",
        "Generated by `make gate3-reports` from the deterministic simulator. A test fails if this file differs from a fresh run.",
        "",
        f"> **All values are `SYNTHETIC`.** {' '.join(config.scenario.disclosure.split())} AETHER Field is a fictional industrial production environment.",
        "",
        "## Definition",
        "",
        f"Fictional Well {config.scenario.target_well} delivers through gathering segment {config.scenario.restricted_segment}. A restriction develops in that segment, which raises flow resistance and upstream backpressure. No Petrobras 3W or other source telemetry is used.",
        "",
        "The model and its assumptions are in the [synthetic telemetry specification](../../docs/product/synthetic_telemetry_spec.md).",
        "",
        "## Parameters",
        "",
        "| Parameter | Value | Display |",
        "|---|---:|---:|",
        f"| Shut-in wellhead pressure | {well.shut_in_wellhead_pressure_pa_abs:,.0f} Pa abs | {_psi(well.shut_in_wellhead_pressure_pa_abs)} psia |",
        f"| Downstream boundary pressure | {segment.downstream_boundary_pressure_pa_abs:,.0f} Pa abs | {_psi(segment.downstream_boundary_pressure_pa_abs)} psia |",
        f"| Ambient pressure | {ambient:,.0f} Pa abs | {_psi(ambient)} psia |",
        f"| Deliverability coefficient, exponent | {well.deliverability_coefficient:.2e}, {well.deliverability_exponent} | |",
        f"| Segment length, internal diameter | {segment.length_m:,.0f} m, {segment.internal_diameter_m} m | |",
        f"| Restricted length | {segment.restricted_length_m:.0f} m | |",
        f"| Darcy friction factor | {segment.darcy_friction_factor} | |",
        f"| Gas molar mass, Z, temperature | {gas.molar_mass_kg_per_mol} kg/mol, {gas.compressibility_factor}, {gas.temperature_k:.0f} K | |",
        f"| Maximum severity (diameter loss) | {schedule.max_severity:.0%} | |",
        f"| Known fault onset | {schedule.onset_offset_s:,} s | day {schedule.onset_offset_s / DAY:.0f} |",
        f"| Full severity reached | {schedule.full_severity_offset_s:,} s | day {schedule.full_severity_offset_s / DAY:.0f} |",
        f"| Sampling | {interval} s for {config.sampling.duration_s:,} s | {len(frame):,} samples |",
        f"| Random seed | {config.simulator.seed} | |",
        "",
        "## Noiseless response of the fault case",
        "",
        "| Day | Severity | State | Flow (sm3/s) | Flow (k sm3/d) | Wellhead (Pa abs) | Wellhead (psig) | Differential (Pa) | Differential (psi) |",
        "|---:|---:|---|---:|---:|---:|---:|---:|---:|",
    ]
    for day in days:
        row = frame[frame["offset_s"] == day * DAY].iloc[0]
        wellhead = row["truth_wellhead_pressure_pa_abs"]
        lines.append(
            f"| {day} | {row['truth_severity']:.3f} | {row['truth_fault_state']} "
            f"| {row['truth_gas_flow_sm3_per_s']:.4f} | {row['truth_gas_flow_sm3_per_s'] * SM3S_TO_KSM3D:.1f} "
            f"| {wellhead:,.0f} | {_psi(wellhead - ambient)} "
            f"| {row['truth_differential_pressure_pa']:,.0f} | {_psi(row['truth_differential_pressure_pa'])} |"
        )
    start, end = frame.iloc[0], frame.iloc[-1]
    flow_change = end["truth_gas_flow_sm3_per_s"] / start["truth_gas_flow_sm3_per_s"] - 1
    dp_change = end["truth_differential_pressure_pa"] / start["truth_differential_pressure_pa"] - 1
    half = frame[frame["truth_severity"] >= schedule.max_severity / 2].iloc[0]
    half_dp = half["truth_differential_pressure_pa"] / start["truth_differential_pressure_pa"] - 1
    lines += [
        "",
        f"Flow falls {abs(flow_change):.1%} and the differential rises {dp_change:.1%} by full severity. The response is strongly nonlinear: at half the final severity, the differential has risen only {half_dp:.1%}, because resistance scales with `D^-5`. Downstream pressure is fixed by a model assumption, so it doesn't respond. Gate 4 replaces that boundary.",
        "",
        "## Sensors",
        "",
        "| Tag | Asset | Column | Reference | Unit | Display | Noise (1 sigma) |",
        "|---|---|---|---|---|---|---:|",
    ]
    for sensor in config.sensors:
        lines.append(
            f"| `{sensor.tag}` | {sensor.asset_id} | `{sensor.column}` | {sensor.reference} | {sensor.unit} | {sensor.display_unit} | {sensor.noise_std:g} |"
        )
    lines += [
        "",
        "## Physical invariants",
        "",
        "| Invariant | Nominal | Measured | Fault | Measured |",
        "|---|---|---|---|---|",
    ]
    for left, right in zip(results["nominal"][1], results["fault"][1], strict=True):
        lines.append(
            f"| `{left.name}` | {'PASS' if left.passed else 'FAIL'} | {_stable(left.measured)} "
            f"| {'PASS' if right.passed else 'FAIL'} | {_stable(right.measured)} |"
        )
    events = results["fault"][2]
    lines += [
        "",
        "Measured values are residuals, limits, or extremes for each check. These are consistency checks on this model, not a validation against a real system.",
        "",
        "## Events",
        "",
        "The nominal case emitted no events. The fault case emitted:",
        "",
        "| Kind | Target | Affected | Offset (s) | Offset (days) | Basis |",
        "|---|---|---|---:|---:|---|",
    ]
    for event in events:
        basis = event.evidence.get("basis") or event.evidence.get("note")
        lines.append(
            f"| `{event.event_kind.value}` | {event.target_asset_id} | {event.affected_asset_id} "
            f"| {event.onset_offset_s:,} | {(event.onset_offset_s or 0) / DAY:.2f} | {basis} |"
        )
    rule = config.integration_proof_rule
    lines += [
        "",
        f"The rule is `{rule.sensor_column}` above its first-{rule.baseline_duration_s / 3600:.0f}-hour mean plus {rule.sigma_multiplier:g} standard deviations, for {rule.consecutive_samples} consecutive samples. It reads sensor columns only.",
        "",
        "**This isn't a detection result.** The gap between onset and the rule's event comes from one seed of one fixed scenario, with no evaluation and no false-alarm measurement. Gate 5 owns detection.",
        "",
        "## Prepared for later workflows",
        "",
        "The fault case writes `fault_prioritization_input.json` in the `PrioritizationInput` shape, naming the event, the assets, the evidence, and the disclosure. It contains no score and no recommendation. Gate 7 owns those.",
        "",
        "## Reproducibility",
        "",
        "| Item | SHA-256 |",
        "|---|---|",
        f"| Validated configuration | `{config.canonical_sha256()}` |",
        f"| Nominal run | `{nominal.canonical_sha256()}` |",
        f"| Fault run | `{fault.canonical_sha256()}` |",
        "",
        "Run hashes cover rounded values, so last-bit floating-point differences don't change them. Regenerate with `make scenario`. Output Parquet goes to the gitignored `data/gold/`.",
        "",
        "## Limits",
        "",
        "- Not calibrated to any real well, and no parameter comes from field data.",
        "- Single-phase, isothermal, and quasi-steady, with fixed boundary pressures.",
        "- One well and one segment. Gate 4 extends this to the facility.",
        "- Noise is independent Gaussian, with no drift or sensor failures.",
        "- Later steps in the specification's section 22, from recommendations onward, belong to Gates 7 and 8.",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(render(load_config()))
    print(f"wrote {REPORT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
