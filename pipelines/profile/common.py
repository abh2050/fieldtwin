"""Shared helpers for profiling. Checks report measured values and can fail; none is forced."""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

PASS, WARN, FAIL = "PASS", "WARN", "FAIL"


@dataclass
class Check:
    name: str
    status: str
    measured: Any
    rule: str


def threshold(name: str, value: float, passing: float, rule: str, floor: float = 0.0) -> Check:
    """PASS at or above `passing`, FAIL at or below `floor`, otherwise WARN."""
    if value >= passing:
        status = PASS
    elif value <= floor:
        status = FAIL
    else:
        status = WARN
    return Check(name, status, round(value, 4), rule)


def zero_expected(name: str, value: int, rule: str, severity: str = FAIL) -> Check:
    return Check(name, PASS if value == 0 else severity, int(value), rule)


def latest_complete(root: Path, source: str) -> dict[str, Any]:
    from pipelines.acquire.common.core import COMPLETE, load_manifests

    done = [m for m in load_manifests(root, source) if m["processing_status"] == COMPLETE]
    if not done:
        raise FileNotFoundError(f"No completed {source} batch. Run `make acquire`.")
    return max(done, key=lambda m: m["ingestion_timestamp"])


def write_report(root: Path, name: str, report: dict[str, Any], checks: list[Check]) -> Path:
    """Write the JSON report and a short Markdown view of the same values."""
    report = {
        **report,
        "summary": {s: sum(c.status == s for c in checks) for s in (PASS, WARN, FAIL)},
        "checks": [asdict(c) for c in checks],
    }
    folder = root / "reports" / "data_quality"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{name}.json"
    path.write_text(json.dumps(report, indent=2, default=str) + "\n")

    lines = [
        f"# {name}: data quality",
        "",
        f"Batch: `{report.get('batch_id')}`. Generated by `make profile` from `{path.name}`.",
        "",
        "| Check | Status | Measured | Rule |",
        "|---|---|---|---|",
    ]
    for check in checks:
        lines.append(f"| {check.name} | {check.status} | {check.measured} | {check.rule} |")
    path.with_suffix(".md").write_text("\n".join(lines) + "\n")
    return path
