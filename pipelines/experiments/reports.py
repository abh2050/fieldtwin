def _load(name: str) -> dict | None:
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def _f(value, digits: int = 3) -> str:
    if value is None or value != value:
        return "n/a"
    return f"{value:.{digits}f}"


def _interval(result: dict, key: str, digits: int = 3) -> str:
    bounds = result.get("interval", {}).get(key)
    return f"{_f(bounds[0], digits)} to {_f(bounds[1], digits)}" if bounds else "not reported"


def _count_cell(counts: dict, key: str) -> str:
    return f"{counts[key]['detected']} of {counts[key]['events']}" if key in counts else "n/a"


def _delay_cell(delays: dict, key: str) -> str:
    if key not in delays:
        return "none detected"
    return f"{delays[key]['median_hours']:.1f} h ({delays[key]['detected']} detected)"


def _context_cell(context: dict, key: str) -> str:
    return f"{context['false_alarms'][key]} in {context['hours'][key]:.0f} h"


def _write(path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n")


def _method_table(methods: dict, *, sample_level: bool = True) -> list[str]:
    lines = [
        "| Method | Events detected | Event recall | Chance level | Skill (95% interval) | False alarms per hour (95% interval) | Time in alarm | Alarm running at onset |",
        "|---|---:|---:|---:|---|---|---:|---:|",
    ]
    for method in METHODS:
        if method not in methods:
            continue
        result = methods[method]
        s = result["summary"]
        recall = "withheld" if s.get("event_recall_withheld") else _f(s["event_recall"])
        lines.append(
            f"| {LABEL[method]} | {s['events_detected']} of {s['events']} | {recall} | {_f(s.get('chance_event_recall'))} | "
            f"{_f(s.get('event_skill'))} ({_interval(result, 'event_skill')}) | {_f(s['false_alarms_per_hour'])} ({_interval(result, 'false_alarms_per_hour')}) | "
            f"{_f(s.get('time_in_alarm'))} | {s['active_at_onset_not_counted']} |"
        )
    if sample_level:
        lines += [
            "",
            "Sample level, at the same thresholds. These count windows, not events.",
            "",
            "| Method | Precision | Recall | F1 | False-positive rate | Average precision |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for method in METHODS:
            if method not in methods:
                continue
            s = methods[method]["summary"]
            ap = methods[method].get(
                "average_precision", methods[method].get("mean_fold_average_precision")
            )
            lines.append(
                f"| {LABEL[method]} | {_f(s['precision'])} | {_f(s['recall'])} | {_f(s['f1'])} | {_f(s['false_positive_rate'], 4)} | {_f(ap)} |"
            )
    return lines


def _selection(selection: dict) -> list[str]:
    preferred = str(selection.get("preferred"))
    return [
        f"**Preferred under the declared rule: {LABEL.get(preferred, 'none')}.** {selection.get('reason', '')}",
        "",
        f"Tied methods: {', '.join(LABEL[m] for m in selection.get('tied', [])) or 'none'}.",
    ]


