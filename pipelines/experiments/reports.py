    if dataset:
        lines += [
            "",
            "## Benchmark generation",
            "",
            f"All {dataset['cases']} AETHER cases ran under the same guard with a 180 s limit. Outcomes: {dataset['outcomes']}. The slowest took {dataset['max_case_seconds']} s.",
        ]
    lines += [
        "",
        "## The Gate 4 hang",
        "",
        "One shell run hung for more than 500 s in Gate 4, and its cause was never found. **It is not claimed fixed.** "
        "No hang occurred in these runs, including repeated runs of the propagation comparison that was running at the time. "
        "That shows only that it didn't recur here. A hang would now be stopped at its timeout and leave a stack trace.",
    ]
    _write(SIMULATION / "reliability_stress.md", lines)


