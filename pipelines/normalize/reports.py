"""Generate the Gate 2 units and compatibility reports from contracts and the real database."""

from __future__ import annotations

from collections import Counter
from typing import Any

import psycopg
import yaml

from packages.repositories.database import REPO_ROOT, connect

from .seed import contract

UNITS_REPORT = REPO_ROOT / "reports" / "data_quality" / "production_units.md"
COMPATIBILITY_REPORT = REPO_ROOT / "reports" / "reconciliation" / "semantic_compatibility.md"
LABELS = {
    "DIRECTLY_COMPATIBLE": "Directly compatible",
    "CONDITIONALLY_COMPATIBLE": "Conditionally compatible",
    "INCOMPATIBLE": "Incompatible",
    "INSUFFICIENT_EVIDENCE": "Insufficient evidence",
}


def _rows(conn: psycopg.Connection, sql: str) -> list[tuple[Any, ...]]:
    return conn.execute(sql).fetchall()


def _one(conn: psycopg.Connection, sql: str) -> Any:
    return _rows(conn, sql)[0][0]


def render_units_report(conn: psycopg.Connection) -> str:
    data = contract("ocd_production_units.yaml")
    codes = yaml.safe_load((REPO_ROOT / "data_contracts/sources/nm_ocd_codes.yaml").read_text())
    references = data["references"]
    total = _one(conn, "SELECT count(*) FROM production_records")
    by_kind = _rows(
        conn,
        """SELECT product_kind, unit_id, count(*), sum(reported_volume),
                  count(*) FILTER (WHERE reported_volume = 0), count(*) FILTER (WHERE reported_volume IS NULL)
           FROM production_records GROUP BY 1, 2 ORDER BY 1""",
    )
    period = _rows(
        conn, "SELECT min(reporting_period), max(reporting_period) FROM production_records"
    )[0]
    months = _rows(
        conn,
        "SELECT reporting_period, count(*) FROM production_records GROUP BY 1 ORDER BY 1 DESC LIMIT 3",
    )
    amended = _one(
        conn,
        "SELECT round(100.0 * count(*) FILTER (WHERE is_amended) / count(*), 1) FROM production_records",
    )
    duplicates = _one(
        conn,
        """SELECT count(*) FROM (SELECT 1 FROM production_records
           GROUP BY reporting_entity_id, reporting_period, product_kind HAVING count(*) > 1) d""",
    )
    before = _one(
        conn, "SELECT count(*) FROM production_records WHERE source_effective_at < reporting_period"
    )
    same_month = _one(
        conn,
        "SELECT count(*) FROM production_records WHERE date_trunc('month', source_effective_at) = reporting_period",
    )
    original_timing = _rows(
        conn,
        """SELECT count(*) FILTER (WHERE source_effective_at <= reporting_period + interval '2 months 15 days'),
                  count(*)
           FROM production_records WHERE NOT is_amended""",
    )[0]
    statuses = _rows(
        conn,
        "SELECT completion_status_code, count(*) FROM production_records GROUP BY 1 ORDER BY 2 DESC",
    )
    ratio = _one(
        conn,
        """SELECT round(percentile_cont(0.5) WITHIN GROUP (ORDER BY gas_volume_mcf_15025psia_60f * 1000.0 / oil_volume_bbl)::numeric, 0)
           FROM v_production_wide WHERE oil_volume_bbl > 0 AND gas_volume_mcf_15025psia_60f > 0""",
    )
    entities = _one(conn, "SELECT count(DISTINCT reporting_entity_id) FROM production_records")
    batch = _one(conn, "SELECT batch_id FROM ingestion_batches WHERE source_system_id='nm_ocd'")

    lines = [
        "# OCD production units and reporting grain",
        "",
        f"Generated by `make gate2-reports` from [the unit contract](../../data_contracts/semantic_mappings/ocd_production_units.yaml) and batch `{batch}`.",
        "",
        "**Result:** gas, oil, and water units are verified against OCD's reporting instructions and the state rule. The database refuses a production row that doesn't match a verified rule. `eff_dte` remains unresolved and isn't used as a production or filing date.",
        "",
        "## Verified units",
        "",
        "| Code | Product scope | Unit | Base conditions | Status |",
        "|---|---|---|---|---|",
    ]
    for rule in data["rules"]:
        lines.append(
            f"| `{rule['product_kind']}` | {rule['product_scope']} | `{rule['unit_id']}` | {rule['base_conditions']} | {rule['verification_status']} |"
        )
    lines += ["", "Two scope details matter when using these values:", ""]
    lines += [
        "- Gas volumes include CO2, so they aren't pure hydrocarbon gas.",
        "- The oil code covers crude oil and condensate together.",
        "",
        "## Evidence",
        "",
    ]
    for rule in data["rules"]:
        lines.append(f"**`{rule['product_kind']}`**")
        lines.append("")
        for item in rule["evidence"]:
            page = f", PDF page {item['page']}" if "page" in item else ""
            lines.append(f'- {references[item["ref"]]["title"]}{page}: "{item["quote"]}"')
        lines.append("")
    lines += ["| Document | Retrieved copy SHA-256 | URL |", "|---|---|---|"]
    for reference in references.values():
        lines.append(f"| {reference['title']} | `{reference['sha256']}` | {reference['url']} |")
    lines += [
        "",
        "## Reporting grain",
        "",
        f"Production is reported per **well completion, month, and product**: {total:,} rows across {entities} completions. A completion is an API number and pool. Rows aren't summed, split, or allocated. `v_production_wide` only pivots products at the same grain.",
        "",
        f"Rows sharing a completion, month, and product: **{duplicates}**.",
        "",
        "| Code | Unit | Rows | Total volume | Zero rows | Null rows |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for kind, unit, count, volume, zero, null in by_kind:
        lines.append(f"| `{kind}` | `{unit}` | {count:,} | {volume:,} | {zero} | {null} |")
    lines += [
        "",
        f"As a plausibility check only, the median gas-oil ratio is {ratio:,} scf/bbl where both products exist. That is a gas-weighted value, consistent with wells typed as gas, but it isn't evidence for the units.",
        "",
        "## Production date versus filing and effective dates",
        "",
        "| Field | Status | Canonical column | Meaning |",
        "|---|---|---|---|",
        f"| `prodn_yr`, `prodn_mth` | {data['dates']['production_date']['status']} | `reporting_period` | {data['dates']['production_date']['meaning']} |",
        f"| `eff_dte` | {data['dates']['eff_dte']['status']} | `source_effective_at` | {' '.join(data['dates']['eff_dte']['meaning'].split())} |",
        f"| `mod_dte` | {data['dates']['mod_dte']['status']} | `source_modified_at` | {data['dates']['mod_dte']['meaning']} |",
        f"| Filing deadline | {data['dates']['filing_deadline']['status']} | Not stored | {data['dates']['filing_deadline']['meaning']} |",
        "",
        "Measured against this batch:",
        "",
        f"- `eff_dte` before the production month: {before} rows.",
        f"- `eff_dte` inside the production month: {same_month} rows.",
        f"- Non-amended rows with `eff_dte` by the 15th of the second following month: {original_timing[0]:,} of {original_timing[1]:,}.",
        "",
        "These patterns suggest a processing time, but OCD doesn't define the field that way, so it stays unresolved.",
        "",
        "## Amendments",
        "",
        " ".join(data["amendments"]["meaning"].split()),
        "",
        f"In this batch, {amended}% of rows have `amend_ind = Y`. The one-row-per-key count above agrees with replacement. A consumer sees the latest report only, and revision history can't be rebuilt from one extract.",
        "",
        "## Period coverage",
        "",
        f"The window runs from {period[0]} to {period[1]}. The most recent months have these row counts:",
        "",
        "| Month | Rows |",
        "|---|---:|",
    ]
    lines += [f"| {month} | {count:,} |" for month, count in months]
    lines += [
        "",
        "The latest month is partial because of the filing lag. Treat it as incomplete rather than as a production drop.",
        "",
        "## Completion status codes",
        "",
        "Decoded with the C-115 instructions.",
        "",
        "| Code | Meaning | Rows |",
        "|---|---|---:|",
    ]
    decode = codes["c115_completion_status"]
    lines += [
        f"| `{code}` | {decode.get(code, 'Undocumented')} | {count:,} |" for code, count in statuses
    ]
    lines += ["", "## Unresolved", ""]
    lines += [f"- {item}" for item in data["unresolved"]]
    lines += [
        "- The meaning of `eff_dte` (above).",
        "- Whether a missing oil or water row means zero. Gas has zero-volume rows, but oil and water have none, so absent rows may mean zero or not reported. `v_production_wide` keeps them NULL.",
    ]
    return "\n".join(lines) + "\n"


def _table(entries: list[dict[str, Any]], key: str, classification: str) -> list[str]:
    chosen = [e for e in entries if e["classification"] == classification]
    if not chosen:
        return ["None.", ""]
    lines = []
    for entry in chosen:
        location = f" ({entry['location']})" if entry.get("location") else ""
        lines.append(f"**`{entry[key]}`**{location}")
        lines.append("")
        lines.append(entry["reasoning"])
        if entry.get("conditions"):
            lines.append("")
            lines.append("Conditions:")
            lines.append("")
            lines += [f"- {condition}" for condition in entry["conditions"]]
        lines.append("")
    return lines


def render_compatibility_report() -> str:
    data = contract("3w_aether_compatibility.yaml")
    variables, events = data["variables"], data["events"]
    variable_counts = Counter(v["classification"] for v in variables)
    event_counts = Counter(e["classification"] for e in events)
    lines = [
        "# Petrobras 3W compatibility with AETHER Field",
        "",
        "Generated by `make gate2-reports` from [the compatibility contract](../../data_contracts/semantic_mappings/3w_aether_compatibility.yaml). The contract is also seeded into `domain_compatibility_assessments`, where it controls scenario mappings.",
        "",
        "> AETHER Field is a fictional industrial production environment. Public industrial datasets have been used for source-grounded experiments, while cross-source asset associations and operational scenarios are explicitly simulated.",
        "",
        "## Conclusions",
        "",
    ]
    lines += [f"- {item}" for item in data["conclusions"]]
    lines += [
        "",
        "**Status of this assessment:** engineering judgment from published definitions, version "
        f"{data['assessment_version']}, dated {data['assessed_on']}. It wasn't validated by a field engineer, a hydraulic calculation, or measurements from a gas well.",
        "",
        "## Summary",
        "",
        "| Classification | Variables | Event classes |",
        "|---|---:|---:|",
    ]
    for key, label in LABELS.items():
        lines.append(f"| {label} | {variable_counts[key]} | {event_counts[key]} |")
    lines.append(f"| **Total** | **{len(variables)}** | **{len(events)}** |")
    lines += [
        "",
        "## What was compared",
        "",
        "**Source (3W):**",
        "",
    ]
    lines += [f"- {item}" for item in data["source_basis"]]
    facility = yaml.safe_load((REPO_ROOT / "config/facility/aether_field.yaml").read_text())
    assumptions = facility["equipment_assumptions"]
    lines += [
        "",
        "**Target (a fictional AETHER well), as declared in the facility configuration:**",
        "",
        f"- Environment: {assumptions['environment']}. Fluid: {assumptions['fluid_regime']}. Lift: {assumptions['lift_method']}.",
        f"- Has: {', '.join(assumptions['has'])}.",
        f"- Doesn't have: {', '.join(assumptions['does_not_have'])}.",
        f"- Not yet defined: {', '.join(assumptions['not_yet_defined'])}.",
        "",
        "These are design assumptions about a fictional asset. Choosing different equipment would change some results, so they're recorded rather than implied.",
        "",
        "## Requirements for applying telemetry to an experimental asset",
        "",
        "| ID | Category | Requirement | Target | Why |",
        "|---|---|---|---|---|",
    ]
    for requirement in data["requirements"]:
        lines.append(
            f"| {requirement['id']} | {requirement['category']} | {requirement['requirement']} | {requirement['target_value']} | {requirement['rationale']} |"
        )
    lines += ["", "## Event classes", ""]
    for key, label in LABELS.items():
        lines += [f"### {label}", ""]
        lines += _table(events, "event", key)
    lines += ["## Variables", ""]
    for key, label in LABELS.items():
        lines += [f"### {label}", ""]
        lines += _table(variables, "tag", key)
    lines += [
        "## How this is enforced",
        "",
        "| Rule | Mechanism |",
        "|---|---|",
        "| An offshore tag can't map to an onshore measurement | `sensor_tag_mappings` foreign keys require the same equipment class |",
        "| An unknown pressure reference can't become gauge | The same keys require the same reference type |",
        "| An incompatible event can't reach an AETHER asset | `scenario_mapping_guard` trigger |",
        "| A conditional event needs evidence for every condition | `scenario_mapping_guard` trigger |",
        "| A mapping can't be OBSERVED or overwrite source identity | Check constraint, composite key, and an immutability trigger |",
        "",
        "Tests that attempt each of these are in `tests/provenance/test_database_invariants.py`.",
        "",
        "## Consequence for AETHER-FAULT-001",
        "",
        "The original scenario replayed a 3W event against a fictional well. That is no longer the default path:",
        "",
        "1. 3W stays a separate benchmark for detection methods, evaluated on its own terms.",
        "2. AETHER telemetry should come from a future physics-constrained synthetic capability, labeled `SYNTHETIC` (ADR 0010). Gate 2 doesn't build it.",
        "3. `QUICK_RESTRICTION_IN_PCK` and `RAPID_PRODUCTIVITY_LOSS` remain possible qualitative references, but only with evidence for every listed condition.",
        "",
        "## Limitations",
        "",
        "- `dataset.ini` gives names, units, and short descriptions. It doesn't publish well geometry, water depth, fluid composition, or choke location.",
        "- Mechanism statements rest on general engineering knowledge and were not checked against a published gas-well field study.",
        "- AETHER's equipment is chosen, not observed, so this compares 3W with a declared design rather than with a real facility.",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    with connect() as conn:
        UNITS_REPORT.write_text(render_units_report(conn))
    COMPATIBILITY_REPORT.write_text(render_compatibility_report())
    print(f"wrote {UNITS_REPORT.relative_to(REPO_ROOT)}")
    print(f"wrote {COMPATIBILITY_REPORT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
