"""Generate reconciliation reports from the real database. Aggregates only: no individual OCD well."""

from __future__ import annotations

from typing import Any

import psycopg

from packages.reconciliation.provenance import audit_provenance
from packages.repositories.database import REPO_ROOT, connect

FOLDER = REPO_ROOT / "reports" / "reconciliation"
DISCLOSURE = (
    "> AETHER Field is a fictional industrial production environment. Its telemetry is synthetic and "
    "comes from a simplified physical model that is not calibrated to any real well. Public industrial "
    "datasets are used separately, in their own context."
)


def _rows(conn: psycopg.Connection, sql: str) -> list[tuple[Any, ...]]:
    return conn.execute(sql).fetchall()


def _one(conn: psycopg.Connection, sql: str) -> Any:
    return _rows(conn, sql)[0][0]


def _generated(title: str) -> list[str]:
    return [
        f"# {title}",
        "",
        "Generated by `make gate3-reports` from the local canonical database. It shows aggregates only, and individual OCD wells stay in that database.",
        "",
        DISCLOSURE,
        "",
    ]


def render_entity_resolution(conn: psycopg.Connection) -> str:
    lines = _generated("Entity resolution")
    rows = _rows(
        conn,
        """SELECT relationship_type, method, verification_status, provenance_class, count(*)
           FROM reconciliation_decisions WHERE module = 'IDENTITY' GROUP BY 1, 2, 3, 4 ORDER BY 1, 2, 3""",
    )
    wells = _one(
        conn,
        "SELECT count(*) FROM source_assets WHERE source_system_id='nm_ocd' AND asset_type='WELL'",
    )
    three_w = _one(conn, "SELECT count(*) FROM source_assets WHERE source_system_id='petrobras_3w'")
    fictional = _one(conn, "SELECT count(*) FROM assets")
    verified = next((r[4] for r in rows if r[0] == "SAME_AS" and r[2] == "VERIFIED"), 0)
    lines += [
        "## Result",
        "",
        f"All {wells} New Mexico wells were matched between the ArcGIS registry and FTP well history on API number alone. No name or location took part. No identifier connects the {three_w} anonymized 3W wells to any New Mexico well, so that stays unresolved. The {fictional} AETHER assets have no real-world identity to resolve.",
        "",
        "## Decisions",
        "",
        "| Relationship | Method | Status | Provenance | Count |",
        "|---|---|---|---|---:|",
    ]
    lines += [f"| `{r[0]}` | `{r[1]}` | {r[2]} | {r[3]} | {r[4]:,} |" for r in rows]
    lines += [
        "",
        "## Method",
        "",
        "| Comparison | Basis | Outcome |",
        "|---|---|---|",
        f"| OCD registry and well history | Identical API number | {verified} verified |",
        "| Well completion and its well | API number in the reported key | Verified |",
        "| 3W and OCD | No shared identifier | Unresolved, one source-level decision |",
        "| Real asset and AETHER asset | Refused by contract and database | No decision can exist |",
        "",
        "## What this doesn't establish",
        "",
        "The registry and well history are both OCD systems, so a matching API number shows consistent identity across OCD's own records. It doesn't independently confirm that the records are correct. The stored evidence records `channels_are_independent = false`.",
        "",
        "## Rules, with tests",
        "",
        "| Rule | Executable check |",
        "|---|---|",
        "| Matching names don't establish identity | `test_identical_names_without_an_identifier_stay_unresolved` |",
        "| Different identifiers override matching names | `test_identical_names_with_different_identifiers_are_rejected` |",
        "| A real asset can't become a fictional one | `test_real_source_asset_cannot_become_a_fictional_asset`, `test_invalid_decisions_are_refused_by_the_database` |",
        "| Unverified identity can't be built on | `test_unverified_identity_cannot_be_built_on` |",
        "| A reviewer must cite an identifier | `test_approving_identity_needs_an_authoritative_identifier` |",
    ]
    return "\n".join(lines) + "\n"


def render_semantic_validation(conn: psycopg.Connection) -> str:
    lines = _generated("Semantic validation")
    summary = _rows(
        conn,
        """SELECT split_part(subject_id, ':', 1), method, verification_status, count(*)
           FROM reconciliation_decisions WHERE module = 'SEMANTIC' GROUP BY 1, 2, 3 ORDER BY 1, 2, 3""",
    )
    rejected = _one(
        conn,
        "SELECT count(*) FROM reconciliation_decisions WHERE module='SEMANTIC' AND verification_status='REJECTED'",
    )
    unresolved = _one(
        conn,
        "SELECT count(*) FROM reconciliation_decisions WHERE module='SEMANTIC' AND verification_status='UNRESOLVED'",
    )
    lines += [
        "## Result",
        "",
        f"Every sensor keeps the meaning of its own equipment class. All {rejected} attempts to map a 3W sensor onto an AETHER measurement of the same physical quantity were refused. All {unresolved} 3W pressure tags stay unresolved, because the source doesn't state a reference type.",
        "",
        "## Decisions",
        "",
        "| Source | Method | Status | Count |",
        "|---|---|---|---:|",
    ]
    lines += [f"| `{r[0]}` | `{r[1]}` | {r[2]} | {r[3]} |" for r in summary]
    tags = _rows(
        conn,
        """SELECT original_source_tag, physical_quantity, measurement_reference_type, original_unit,
                  canonical_unit, conversion_method, equipment_class_id, data_quality_state
           FROM v_tag_semantics ORDER BY source_system, original_source_tag""",
    )
    lines += [
        "",
        "## Sensor semantics",
        "",
        "| Tag | Quantity | Reference | Unit | Canonical | Conversion | Equipment class | State |",
        "|---|---|---|---|---|---|---|---|",
    ]
    lines += ["| " + " | ".join(f"`{v}`" for v in row) + " |" for row in tags]
    reasons = _rows(
        conn,
        """SELECT d.subject_id, d.object_id, d.evidence->>'refused_because'
           FROM reconciliation_decisions d
           WHERE d.module = 'SEMANTIC' AND d.verification_status = 'REJECTED' AND d.subject_id LIKE '%%PT-P'
           ORDER BY d.object_id""",
    )
    lines += [
        "",
        "## Example refusals: the subsea tag `PT-P`",
        "",
        "`PT-P` and the AETHER definitions below are all pressures in pascals, and the mapping is still refused.",
        "",
        "| AETHER definition | Why it was refused |",
        "|---|---|",
    ]
    lines += [f"| `{r[1]}` | {r[2]} |" for r in reasons]
    lines += [
        "",
        "## Enforcement, with tests",
        "",
        "| Must be rejected | Python | Database |",
        "|---|---|---|",
        "| Offshore sensor to onshore equipment | `test_offshore_sensor_cannot_map_to_onshore_equipment` | `test_offshore_tag_cannot_map_to_onshore_wellhead_pressure` |",
        "| Gauge and absolute confusion | `test_incorrect_pressure_conversions_are_refused`, `test_gauge_tag_cannot_map_to_absolute_definition` | `test_unknown_reference_cannot_be_changed_to_gauge_in_a_mapping` |",
        "| Missing unit definition | `test_missing_unit_definition_is_refused` | `test_unit_must_measure_the_stated_quantity` |",
        "| Unverified identity | `test_unverified_identity_cannot_be_built_on` | `test_verified_identifier_needs_an_asset` |",
        "| Misclassified simulated observation | `test_simulated_observation_must_be_synthetic` | `test_simulated_series_cannot_claim_observed` |",
        "| Invalid equipment relationship | `test_invalid_equipment_relationships_are_refused` | `test_invalid_equipment_relationships_are_refused` |",
        "| Missing provenance | `test_missing_or_unknown_provenance_is_refused` | `test_unknown_provenance_class_is_rejected` |",
        "| 3W event mapped onto AETHER | `test_real_sources_cannot_be_mapped_onto_aether` | `test_conditionally_compatible_3w_event_is_still_refused_by_the_boundary` |",
        "",
        "## Provenance audit on this database",
        "",
        "| Rule | Violations |",
        "|---|---:|",
    ]
    lines += [f"| {f.rule} | {f.violations} |" for f in audit_provenance(conn)]
    lines += [
        "",
        "The physical reasoning behind each 3W classification is in [`semantic_compatibility.md`](semantic_compatibility.md).",
    ]
    return "\n".join(lines) + "\n"


def render_geospatial(conn: psycopg.Connection) -> str:
    lines = _generated("Geospatial associations")
    status = dict(
        _rows(
            conn,
            "SELECT spatial_status::text, count(*) FROM source_assets WHERE source_system_id='nm_ocd' AND asset_type='WELL' GROUP BY 1",
        )
    )
    total, low, median, high, zero = _rows(
        conn,
        """SELECT count(*), min(d), percentile_cont(0.5) WITHIN GROUP (ORDER BY d), max(d), count(*) FILTER (WHERE d = 0)
           FROM (SELECT (evidence->>'distance_m')::float AS d FROM reconciliation_decisions WHERE module='GEOSPATIAL') x""",
    )[0]
    outcomes = _rows(
        conn,
        "SELECT verification_status, provenance_class, count(*) FROM reconciliation_decisions WHERE module='GEOSPATIAL' GROUP BY 1, 2",
    )
    radius = _one(
        conn,
        "SELECT (evidence->>'search_radius_m')::float FROM reconciliation_decisions WHERE module='GEOSPATIAL' LIMIT 1",
    )
    identity = _one(
        conn,
        "SELECT count(*) FROM reconciliation_decisions WHERE method='GEOSPATIAL_PROXIMITY' AND relationship_type='SAME_AS'",
    )
    queue = _one(
        conn, "SELECT count(*) FROM v_reconciliation_review_queue WHERE module='GEOSPATIAL'"
    )
    emissions = _one(
        conn,
        "SELECT count(*) FROM reconciliation_decisions WHERE relationship_type='EMISSION_NEAR'",
    )
    lines += [
        "## Result",
        "",
        f"Proximity gave {total} candidate pairs of wells within {radius:.0f} m, and **none became an identity**. {zero} pairs have identical reported coordinates and remain separate wells with separate API numbers, as wells sharing a pad location can. All of them wait for review.",
        "",
        "## Spatial population",
        "",
        "| Status | Wells | Treatment |",
        "|---|---:|---|",
        f"| Usable | {status.get('USABLE', 0)} | Takes part in proximity analysis |",
        f"| Unresolved datum | {status.get('UNRESOLVED_DATUM', 0)} | Excluded, because OCD's two systems don't name one datum |",
        f"| Quarantined | {status.get('QUARANTINED', 0)} | Excluded, because a coordinate contradicts its reported township |",
        "",
        "Reported values are kept for excluded wells, and their production records stay valid.",
        "",
        "## Candidates",
        "",
        "| Status | Provenance | Pairs |",
        "|---|---|---:|",
    ]
    lines += [f"| {r[0]} | {r[1]} | {r[2]} |" for r in outcomes]
    lines += [
        "",
        f"Distance between paired wells: minimum {low:.1f} m, median {median:.1f} m, maximum {high:.1f} m.",
        "",
        f"Proximity decisions stating identity: **{identity}**. Candidates in the review queue: {queue}.",
        "",
        "## Limits",
        "",
        "- **Distance only.** A pair says two reported points are close. It doesn't say they share equipment, a pad, or an operator.",
        "- **No confidence value.** Distance isn't a probability, so `confidence` stays NULL.",
        "- **No numeric uncertainty.** OCD describes locations as approximate and publishes no figure. Each decision records that statement, and the radius isn't widened to compensate.",
        f"- **Screening radius.** {radius:.0f} m is a parameter for review workload, not a physical threshold.",
        f"- **No emissions data yet.** There are {emissions} `EMISSION_NEAR` decisions, because Carbon Mapper is deferred to Gate 6. The code path exists and is tested with hand-written points only.",
        "- **Not a source attribution.** Nothing here attributes anything to a well.",
        "",
        "## Rules, with tests",
        "",
        "| Rule | Executable check |",
        "|---|---|",
        "| Identical coordinates yield only a candidate | `test_identical_coordinates_produce_only_a_candidate`, `test_wells_at_identical_coordinates_keep_separate_identities` |",
        "| Proximity can't be stored as identity | `test_proximity_cannot_be_stored_as_identity`, `test_invalid_decisions_are_refused_by_the_database` |",
        "| A reviewer can't approve proximity | `test_proximity_cannot_be_approved_even_by_a_reviewer` |",
        "| Excluded coordinates take no part | `test_excluded_coordinates_take_no_part`, `test_excluded_wells_are_never_proximity_candidates` |",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    FOLDER.mkdir(parents=True, exist_ok=True)
    with connect() as conn:
        for name, render in (
            ("entity_resolution.md", render_entity_resolution),
            ("semantic_validation.md", render_semantic_validation),
            ("geospatial_associations.md", render_geospatial),
        ):
            (FOLDER / name).write_text(render(conn))
            print(f"wrote reports/reconciliation/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
